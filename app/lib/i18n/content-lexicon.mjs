const ZH_CN_LEXICAL_MEANINGS = Object.freeze(Object.fromEntries(
  REVIEWED_LEXICAL_SENSES.map(sense => [sense.id, sense.meaning]),
));

export const LEXICAL_MEANINGS_BY_LOCALE = Object.freeze({
  'zh-CN': ZH_CN_LEXICAL_MEANINGS,
  en: EN_LEXICAL_MEANINGS,
});

/** Return the complete immutable lexical-meaning map for a supported locale. */
export function lexicalMeaningsForLocale(locale = DEFAULT_LOCALE) {
  const normalized = normalizeLocale(locale);
  if (!normalized || !Object.hasOwn(LEXICAL_MEANINGS_BY_LOCALE, normalized)) {
    throw new RangeError(`Unsupported lexical locale: ${String(locale)}`);
  }
  return LEXICAL_MEANINGS_BY_LOCALE[normalized];
}

/** Return one localized meaning by stable sense ID, or null for an unknown sense. */
export function lexicalMeaningFor(senseOrId, locale = DEFAULT_LOCALE) {
  const id = typeof senseOrId === 'string' ? senseOrId : senseOrId?.id;
  if (typeof id !== 'string') return null;
  return lexicalMeaningsForLocale(locale)[id] ?? null;
}

export const getLexicalMeaning = lexicalMeaningFor;
