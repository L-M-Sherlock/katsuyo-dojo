#!/usr/bin/env node
// Materialize only fully reviewed cards. The historical audit proof stays immutable.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import zlib from 'node:zlib';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {USER_DIRECTED_USAGE_DEFERRALS} from '../app/lib/usage-cards/user-directed-deferrals.mjs';
import {RETIRED_TEORU_NEGATIVE_FORMS} from '../app/lib/compound-forms.mjs';

const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const proofPath = path.join(project, 'docs/usage-card-naturalness-full-progress.v1.json.gz');
const overlayPath = path.join(project, 'app/lib/usage-cards/full-naturalness-overlay.mjs');
const proof = JSON.parse(zlib.gunzipSync(fs.readFileSync(proofPath)));
const hash = value => crypto.createHash('sha256').update(JSON.stringify(value)).digest('hex');
const assert = (condition, message) => { if (!condition) throw Error(message); };

const statuses = new Map(proof.statuses.map(row => [row.id, row]));
const source = new Map(proof.sourceCards.map(card => [card.id, card]));
assert(source.size === proof.activeCount && statuses.size === source.size,
  'Frozen source or final status has duplicate or missing card IDs');
assert(proof.statuses.every(row => row.status === 'approved' || row.status === 'deferred'),
  `Naturalness review is incomplete: ${JSON.stringify(proof.counts)}`);

const changed = new Map();
for (const repair of proof.repairs) {
  const cards = new Map(repair.draft.map(card => [card.id, card]));
  for (const row of repair.rows.filter(row => row.status === 'approved')) {
    const card = cards.get(row.id);
    assert(card && hash(card) === row.hash, `Approved repair proof drift: ${repair.repairId}/${row.id}`);
    changed.set(row.id, {...card, review: 'approved'});
  }
}
const deferred = new Set(proof.deferrals.map(row => row.id));
const userDeferred = new Map(USER_DIRECTED_USAGE_DEFERRALS.map(row => [row.id, row]));
assert(userDeferred.size === USER_DIRECTED_USAGE_DEFERRALS.length
  && new Set(USER_DIRECTED_USAGE_DEFERRALS.map(row => row.pair)).size === userDeferred.size,
  'User-directed holds have duplicate cards or pairs');
const replacements = [];
const deferredPairs = [];
for (const card of proof.sourceCards) {
  const status = statuses.get(card.id);
  assert(status.sourceHash === hash(card), `Frozen card hash drift: ${card.id}`);
  if (status.status === 'deferred') {
    assert(deferred.has(card.id), `Missing exact deferral proof: ${card.id}`);
    deferredPairs.push(`${card.senseId}/${card.form}`);
    continue;
  }
  const replacement = changed.get(card.id);
  const held = userDeferred.get(card.id);
  if (held) {
    assert(status.status === 'approved' && held.pair === `${card.senseId}/${card.form}`
      && held.cardHash === hash(replacement ?? card), `User-directed hold is stale: ${card.id}`);
    userDeferred.delete(card.id);
  }
  if (replacement) {
    assert(status.cardHash === hash(replacement), `Final revision hash drift: ${card.id}`);
    replacements.push(replacement);
  } else assert(status.cardHash === hash(card), `Unchanged approval hash drift: ${card.id}`);
}
assert(deferred.size === deferredPairs.length && new Set(deferredPairs).size === deferredPairs.length,
  'Deferral count or pair scope drift');
assert(userDeferred.size === 0, `User-directed holds are absent from the approved proof: ${[...userDeferred.keys()]}`);

const generated = '// Generated by scripts/build-naturalness-overlay.mjs from the complete exact-hash audit.\n'
  + `export const FULL_NATURALNESS_REPLACEMENTS = ${JSON.stringify(replacements, null, 2)};\n`
  + `export const FULL_NATURALNESS_DEFERRED_PAIRS = new Set(${JSON.stringify(deferredPairs, null, 2)});\n`;
fs.writeFileSync(`${overlayPath}.next`, generated);
fs.renameSync(`${overlayPath}.next`, overlayPath);

const runtime = await import(pathToFileURL(path.join(project, 'app/lib/usage-cards.mjs')).href);
const live = new Map(runtime.USAGE_CARDS.map(card => [card.id, card]));
const heldIds = new Set(USER_DIRECTED_USAGE_DEFERRALS.map(row => row.id));
const retiredIds = new Set(proof.sourceCards.filter(card => RETIRED_TEORU_NEGATIVE_FORMS.has(card.form)).map(card => card.id));
const absentIds = new Set([...deferred, ...heldIds, ...retiredIds]);
assert(live.size === proof.activeCount - absentIds.size,
  `Runtime card count after overlay is wrong: ${live.size}`);
for (const row of proof.statuses) {
  const card = live.get(row.id);
  if (absentIds.has(row.id)) assert(!card, `Deferred or retired card remains active: ${row.id}`);
  else assert(card && hash(card) === row.cardHash, `Runtime card differs from reviewed text: ${row.id}`);
}
console.log(JSON.stringify({active: live.size, replacements: replacements.length,
  deferred: deferredPairs.length, userDirectedHolds: heldIds.size,
  retiredForms: [...RETIRED_TEORU_NEGATIVE_FORMS], retiredCards: retiredIds.size,
  overlay: path.relative(project, overlayPath)}));
